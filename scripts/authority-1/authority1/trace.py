"""Markdown traces: one unit, all three arms, every prompt and reply as sent and returned."""
from __future__ import annotations

import json

from .specs import SPECS


def fence(t, lang=""):
    t = (t or "").replace("```", "ʼʼʼ")
    return f"```{lang}\n{t}\n```"


def call_md(c):
    u = c.get("usage") or {}
    head = (f"**{c['lane']}** — {u.get('prompt_tokens')} in / {u.get('completion_tokens')} out"
            f" (reasoning {u.get('reasoning_tokens')}), ${c.get('cost') or 0:.5f}, {c.get('latency_ms')} ms, host {c.get('provider')}, "
            f"finish `{c.get('finish_reason')}`{' · REFUSED' if c.get('refused') else ''}{' · error: ' + str(c.get('error')) if c.get('error') else ''}")
    return "\n".join([head, "", "<details><summary>prompt as sent</summary>", "", fence(c.get("prompt")), "", "</details>", "",
                      "reply as returned:", "", fence(c.get("text")), ""])


def unit_md(u, s, judged=True):
    lines = [f"### {s['id']} — {s['title']} (class {s['class']}), {SPECS[u['spec']]['label']}, repeat {u['repeat']}", ""]
    lines += [f"**Change** ({s['change']['kind']}, {s['change']['date']}): {s['change']['text']} Revokes: {', '.join(s['change']['revokes']) or '—'}.", "",
              f"**Task:** {s['task']['text']} — options " + "; ".join(f"{o['id']}) {o['text']}" for o in s["task"]["options"]), "",
              f"**Truth table:** correct {s['truth']['correct_options']}, stale {s['truth']['stale_options']}, touched "
              + ", ".join(f"{t['id']} ({t['direction']})" for t in s["truth"]["touched"]) + f"; untouched {s['truth']['untouched']}; obligations due {s['truth']['obligations_due']}.", ""]
    ing = u["ingest"]
    lines += ["#### Mem0 takes in the change (infer=True, the subject model as Mem0's LLM)", "",
              f"Mem0 stored: " + "; ".join(f"«{r.get('memory')}» ({r.get('event')})" for r in ing.get("results") or []) + (f" — error: {ing['error']}" if ing.get("error") else ""), ""]
    for c in ing.get("mem0_calls") or []:
        uu = c.get("usage") or {}
        lines += [f"Mem0's own call: {uu.get('prompt_tokens')} in / {uu.get('completion_tokens')} out, ${c.get('cost') or 0:.5f}, host {c.get('provider')}. Mem0's request (minus messages): `{json.dumps(c.get('mem0_request'))}`. Reply:", "", fence(c.get("text"), "json"), ""]
    lines += [f"#### Mem0 search (task text as query, top_k {len(u['retrieval'])} of {len(u['store'])} memories) — shared by A, B, C", ""]
    lines += [fence("\n".join(f"{r['score']:.3f}  {r['text']}" for r in u["retrieval"]))]
    for arm in ("A", "B", "C"):
        r = u["arms"][arm]
        lines += ["", f"#### Arm {arm}", ""]
        if arm == "C":
            w = r.get("walk") or {}
            lines += [f"Layer walk: roots {w.get('roots')}, walked {w.get('walked')}, paths `{json.dumps(w.get('paths'))}`; marks `{json.dumps(r.get('marks'), ensure_ascii=False)}`", ""]
        for c in r["calls"]:
            lines.append(call_md(c))
        m = r.get("mech") or {}
        lines += [f"**Scored (mechanical):** `{json.dumps(m)}`"]
        if judged and r.get("judge"):
            j = r["judge"]
            lines += [f"**Judges:** final `{json.dumps(j.get('final'))}` by {j.get('by')}"]
        lines += [f"Arm cost ${r.get('cost', 0):.5f}, latency {r.get('latency_ms')} ms (calls), wall {r.get('wall_ms')} ms.", ""]
    return "\n".join(lines)


def issue_comment(dry_md: str, header: str, limit: int = 60000) -> str:
    """The dry-run trace as an issue comment; prompts collapse; trimmed to GitHub's comment size if needed."""
    body = header + "\n\n" + dry_md
    if len(body) > limit:
        body = body[: limit - 400] + "\n\n…(trimmed to fit a GitHub comment; the whole trace is in `docs/runs/authority-1-dry-run.md`)\n"
    return body + "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_\n"
