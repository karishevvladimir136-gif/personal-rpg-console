export function worldLibraryText(
  language: "en" | "ru",
  key: string,
  values: Record<string, string | number> = {},
): string {
  let result = language === "ru" ? (WORLD_LIBRARY_RU[key] ?? key) : key;
  for (const [name, value] of Object.entries(values))
    result = result.replaceAll(`{${name}}`, String(value));
  return result;
}

export function worldLibraryCompilerNote(
  language: "en" | "ru",
  value: string,
): string {
  if (language !== "ru") return value;
  const coverage =
    /^Some source lines remain unindexed \((\d+)\/(\d+)\)\. Originals remain available\.$/.exec(
      value,
    );
  if (coverage)
    return `Часть строк источника не проиндексирована (${coverage[1]}/${coverage[2]}). Оригиналы сохранены.`;
  const identity =
    /^“(.+)” occurs in separate source identities\. They were not merged; review whether they denote the same entity\.$/.exec(
      value,
    );
  if (identity)
    return `«${identity[1]}» встречается в отдельных исходных сущностях. Они не объединены; проверьте, обозначают ли они одну сущность.`;
  return worldLibraryText(language, value);
}
